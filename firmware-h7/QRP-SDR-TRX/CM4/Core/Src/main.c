int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

/* USER CODE BEGIN Boot_Mode_Sequence_1 */
#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
  /*HW semaphore Clock enable*/
  __HAL_RCC_HSEM_CLK_ENABLE();
  /* Activate HSEM notification for Cortex-M4*/
  HAL_HSEM_ActivateNotification(__HAL_HSEM_SEMID_TO_MASK(HSEM_ID_0));
  /*
  Domain D2 goes to STOP mode (Cortex-M4 in deep-sleep) waiting for Cortex-M7 to
  perform system initialization (system clock config, external memory configuration.. )
  */
  HAL_PWREx_ClearPendingEvent();
  HAL_PWREx_EnterSTOPMode(PWR_MAINREGULATOR_ON, PWR_STOPENTRY_WFE, PWR_D2_DOMAIN);
  /* Clear HSEM flag */
  __HAL_HSEM_CLEAR_FLAG(__HAL_HSEM_SEMID_TO_MASK(HSEM_ID_0));

#endif /* DUAL_CORE_BOOT_SYNC_SEQUENCE */
/* USER CODE END Boot_Mode_Sequence_1 */
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* USER CODE BEGIN SysInit */

  /* I2C1 and USART3's clocks (D2PCLK1) derive from the same PLL only CM7's
     SystemClock_Config() configures - with the old Stop-mode boot sync
     disabled (see DUAL_CORE_BOOT_SYNC_SEQUENCE in the defines above),
     CM4 would otherwise race ahead and init them against the pre-config
     default clock (corrupting every OLED transfer - seen on hardware as
     "white dots"/garbage - and giving the UART console a wrong baud
     divisor). Busy-wait instead of the old EnterSTOPMode() wait: same
     synchronization guarantee, but CM4 stays fully awake and debuggable
     rather than falling asleep somewhere a debugger could race against
     on reset. */
  while (*(volatile uint32_t *)(D3_SRAM_BASE + 0x3000UL) == 0) {}

  /* SystemCoreClock is a per-core CACHED variable, not a live register
     read - only CM7 ever calls HAL_RCC_ClockConfig() (which updates it),
     so CM4's own copy was still sitting at its compile-time default
     (~64 MHz, HSI) even though the real shared clock tree was already
     running at the configured rate by this point. I2C1 was unaffected
     since CubeMX hardcodes its Timing register as a constant, but
     HAL_UART_Init() computes the baud divisor at runtime from
     SystemCoreClock, so USART3 got a divisor calculated for ~64 MHz
     applied to a much faster real clock - actual wire baud came out
     ~1.9x too fast, which is exactly consistent bit-level garbage on
     every byte, not occasional corruption. This recomputes it from the
     actual hardware registers (which CM7 already configured, before
     signaling the flag above) rather than relying on CM4's stale cache. */
  SystemCoreClockUpdate();

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_DMA_Init();
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_ADC3_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */

  /* USART3 console - PD8/PD9 is this board's ST-LINK VCP, so no external
     wiring needed. Lives on CM4 rather than CM7: CM4 owns the control
     plane (HMI/IPC) and isn't running the time-critical DSP loop or USB
     Audio class handling, and it already has CM7's live telemetry
     (rx_rms, tx_active, mode, FreeDV sync/SNR) via ipc_cm7_to_cm4_read()
     for any status the console wants to print. */
  __HAL_RCC_USART3_CLK_ENABLE();
  huart3.Instance = USART3;
  huart3.Init.BaudRate = 115200;
  huart3.Init.WordLength = UART_WORDLENGTH_8B;
  huart3.Init.StopBits = UART_STOPBITS_1;
  huart3.Init.Parity = UART_PARITY_NONE;
  huart3.Init.Mode = UART_MODE_TX_RX;
  huart3.Init.HwFlowCtl = UART_HWCONTROL_NONE;
  huart3.Init.OverSampling = UART_OVERSAMPLING_16;
  HAL_UART_Init(&huart3);
  /* HAL_UART_Init() computes BRR as if D2PCLK1 were ~64 MHz (BRR=0x22C)
     rather than the real, confirmed-correct 120 MHz (SWS/PLL1DIVR/D1CFGR/
     D2CFGR all read back exactly as configured; HSE_VALUE is also correct
     at 8 MHz) - traced through UART_SetConfig()'s whole call chain without
     finding why. Empirically verified via direct SWD register write that
     0x412 (the right divisor for 120 MHz/115200 baud) fixes the console
     completely - garbage output before, clean text after. Override HAL's
     result with the known-correct value until the actual discrepancy is
     found. */
  huart3.Instance->BRR = 0x412;
  {
    const char *msg = "CM4 boot OK\r\n";
    HAL_UART_Transmit(&huart3, (uint8_t *)msg, strlen(msg), 1000);
  }

  ipc_mailbox_init();

  hmi_init(&hi2c1);

  console_init(&huart3);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    hmi_poll();
    console_poll();

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

